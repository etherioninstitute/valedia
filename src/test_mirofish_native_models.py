def run_fake_helper(text, downloaded, requests):
    first = text.splitlines()[0]
    assert first.startswith('import {LMStudioClient} from ') and first.endswith("index.mjs';")
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp/'fake_sdk.mjs').write_text(FAKE_SDK)
        (tmp/'spec.json').write_text(json.dumps({'downloaded': downloaded}))
        (tmp/'helper.mjs').write_text(text.replace(first, "import {LMStudioClient} from './fake_sdk.mjs';", 1))
        lines = ''.join(json.dumps(dict(x, id=i+1)) + '\n' for i, x in enumerate(requests))
        done = subprocess.run([str(NODE), str(tmp/'helper.mjs')], input=lines, capture_output=True, text=True, timeout=60, cwd=tmp,
                              env={'PATH': '/usr/bin:/bin', 'FAKE_SDK_SPEC': str(tmp/'spec.json'), 'NODE_DISABLE_COMPILE_CACHE': '1'})
        assert done.returncode == 0, done.stderr
        out = [json.loads(x) for x in done.stdout.splitlines()]
        assert [row['id'] for row in out] == list(range(1, len(requests)+1)), done.stdout
        return out


class ObserverReadTests(unittest.TestCase):
    """R7: the observer reads exactly the tokenizer origins and GGUF files of the plan's profiles."""
    def checkpoint_rules(self, names):
        rules = set()
        for name in names:
            p = m.MODEL_PROFILES[name]
            rules.add('(allow file-read* file-map-executable (subpath "%s"))' % p['tokenizer_root'])
            for f in m.profile_files(name):
                rules.add('(allow file-read* (literal "%s"))' % f['path'])
        return rules

    def test_plan_policy_names_both_profiles_files_and_otherwise_equals_the_single_policy(self):
        code, plan, err = view(PLAN); self.assertEqual(code, 0, err[-600:])
        code, single, err = view(None); self.assertEqual(code, 0, err[-600:])
        plan_rules = self.checkpoint_rules((BONSAI, 'qwen3-8b'))
        lines = plan['policy'].splitlines()
        for rule in plan_rules:
            self.assertEqual(lines.count(rule), 1, rule)
        self.assertNotIn('(allow file-read* (literal "%s"))' % m.MODEL_PROFILES['qwen3.8-27b']['weight_file'], lines)
        single_rules = self.checkpoint_rules(('qwen3.8-27b',))
        self.assertEqual([x for x in lines if x not in plan_rules], [x for x in single['policy'].splitlines() if x not in single_rules])
        self.assertEqual(len(lines) - len(plan_rules), len(single['policy'].splitlines()) - len(single_rules))


