def view(selector=None, registry=None, code=VIEW):
    """Import private copies of the three modules with an optional selector and registry beside them."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for name in ('mirofish_native_model.py', 'mirofish_native_run.py', 'mirofish_native_gateway.py'):
            shutil.copy2(SRC/name, tmp/name)
        if selector is not None:
            (tmp/'mirofish_model_profile.json').write_text(selector if isinstance(selector, str) else json.dumps(selector))
        if registry is not None:
            (tmp/'mirofish_model_registry.json').write_text(registry if isinstance(registry, str) else json.dumps(registry))
        done = subprocess.run([sys.executable, '-B', '-c', code], cwd=tmp, capture_output=True, text=True, timeout=120,
                              env={'PATH': '/usr/bin:/bin', 'TMPDIR': os.environ.get('TMPDIR', '/tmp')})
        return done.returncode, (json.loads(done.stdout) if done.returncode == 0 else None), done.stderr


