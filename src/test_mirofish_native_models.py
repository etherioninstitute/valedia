class SwapTests(unittest.TestCase):
    """R4: the swap at a boundary, with the gateway provably idle, against a fake helper."""
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.gateway = Gateway(Limits(ID), 's'*32, Path(self.tmp.name)/'ledger.json', lambda *a: None, deadline=time.monotonic()+2400)
        self.state = {'profile': BONSAI, 'loaded': loaded_readback(BONSAI, 'ref-1')}
        self.built = []

    def tearDown(self):
        self.tmp.cleanup()

    def admission_for(self, name):
        self.built.append(name); return ('admission', name)

    def swap(self, helper):
        return r.swap_model(helper, self.gateway, ID, 'qwen3-8b', self.state, 'emb-ref', self.admission_for, time.monotonic()+600)

    def clean_unload(self):
        return {'unloaded': ID, 'snapshot': {'llm': [], 'embedding': [{'identifier': 'ym-research-embedding'}]}}

    def test_idle_swap_unloads_loads_rebuilds_admission_and_records_both_readbacks(self):
        helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback('qwen3-8b', 'ref-2'))
        event = self.swap(helper)
        self.assertEqual(helper.calls, [('unload', {'identifier': ID, 'instanceReference': 'ref-1', 'embeddingReference': 'emb-ref', 'profile': BONSAI}),
                                        ('load', {'identifier': ID, 'profile': 'qwen3-8b'})])
        self.assertEqual(self.built, ['qwen3-8b'])
        self.assertEqual(self.gateway.admit_context, ('admission', 'qwen3-8b'))
        self.assertEqual((event['from_profile'], event['to_profile'], event['gateway_calls']), (BONSAI, 'qwen3-8b', 0))
        self.assertEqual((event['unload'], event['load']), (self.clean_unload(), loaded_readback('qwen3-8b', 'ref-2')))
        self.assertEqual(self.state, {'profile': 'qwen3-8b', 'loaded': loaded_readback('qwen3-8b', 'ref-2')})
        self.assertFalse(self.gateway.cancelled.is_set())
        self.assertTrue(self.gateway.serial.acquire(blocking=False)); self.gateway.serial.release()

    def refused(self, helper, pattern):
        before = self.gateway.admit_context
        with self.assertRaisesRegex(NativeRefused, pattern):
            self.swap(helper)
        self.assertTrue(self.gateway.cancelled.is_set(), 'a failed swap freezes the gateway before the serial lock is released')
        self.assertIs(self.gateway.admit_context, before)
        self.assertTrue(self.gateway.serial.acquire(blocking=False)); self.gateway.serial.release()

    def test_busy_gateway_refuses_before_any_model_operation(self):
        for state in ('reserved', 'inflight'):
            self.setUp()
            self.gateway.state['calls'].append({'id': 'busy', 'state': state})
            helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback('qwen3-8b', 'ref-2'))
            self.refused(helper, 'not idle')
            self.assertEqual(helper.calls, [])

    def test_held_serial_lock_refuses_and_is_not_released_by_the_swap(self):
        helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback('qwen3-8b', 'ref-2'))
        holder_ready, release = threading.Event(), threading.Event()
        def hold():
            with self.gateway.serial:
                holder_ready.set(); release.wait(10)
        thread = threading.Thread(target=hold); thread.start(); holder_ready.wait(10)
        try:
            with self.assertRaisesRegex(NativeRefused, 'not idle'):
                self.swap(helper)
            self.assertFalse(self.gateway.serial.acquire(blocking=False), 'the swap released a lock it did not hold')
        finally:
            release.set(); thread.join(10)
        self.assertEqual(helper.calls, []); self.assertTrue(self.gateway.cancelled.is_set())

    def test_cancelled_gateway_refuses(self):
        self.gateway.cancel()
        helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback('qwen3-8b', 'ref-2'))
        self.refused(helper, 'cancelled'); self.assertEqual(helper.calls, [])

    def test_unload_that_leaves_a_language_model_listed_refuses_without_loading(self):
        for reply in [{'unloaded': ID, 'snapshot': {'llm': [{'identifier': 'other'}], 'embedding': []}},
                      {'alreadyAbsent': True, 'snapshot': {'llm': [], 'embedding': []}}, {'unloaded': 'mf-native-'+'1'*32, 'snapshot': {'llm': []}}]:
            self.setUp()
            helper = FakeHelper(unload=reply, load=loaded_readback('qwen3-8b', 'ref-2'))
            self.refused(helper, 'unload')
            self.assertEqual([c[0] for c in helper.calls], ['unload'])
            self.assertEqual(self.state['profile'], BONSAI)

    def test_failed_load_refuses_and_leaves_cleanup_the_next_profile(self):
        helper = FakeHelper(unload=self.clean_unload(), load=NativeRefused('fixed SDK operation refused: load'))
        self.refused(helper, 'load')
        self.assertEqual(self.state, {'profile': 'qwen3-8b', 'loaded': None})
        self.assertEqual(self.built, [])

    def test_load_readback_of_another_checkpoint_refuses(self):
        helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback(BONSAI, 'ref-2'))
        self.refused(helper, 'readback')
        self.assertEqual(self.state, {'profile': 'qwen3-8b', 'loaded': None})

    def test_call_arriving_during_the_swap_refuses_and_admission_is_not_replaced(self):
        def load(values):
            with self.gateway.lock:
                self.gateway.state['calls'].append({'id': 'late', 'state': 'reserved'})
            return loaded_readback('qwen3-8b', 'ref-2')
        helper = FakeHelper(unload=self.clean_unload(), load=load)
        self.refused(helper, 'arrived during the model swap')

    def test_failed_admission_rebuild_refuses(self):
        helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback('qwen3-8b', 'ref-2'))
        def broken(name):
            raise NativeRefused('frozen native model/tokenizer file changed')
        before = self.gateway.admit_context
        with self.assertRaisesRegex(NativeRefused, 'tokenizer file changed'):
            r.swap_model(helper, self.gateway, ID, 'qwen3-8b', self.state, 'emb-ref', broken, time.monotonic()+600)
        self.assertTrue(self.gateway.cancelled.is_set()); self.assertIs(self.gateway.admit_context, before)

    def test_unknown_or_unchanged_next_profile_refuses(self):
        helper = FakeHelper(unload=self.clean_unload(), load=loaded_readback('qwen3-8b', 'ref-2'))
        with self.assertRaises(NativeRefused):
            r.swap_model(helper, self.gateway, ID, BONSAI, self.state, 'emb-ref', self.admission_for, time.monotonic()+600)
        with self.assertRaises(NativeRefused):
            r.swap_model(helper, self.gateway, ID, 'qwen9-900b', self.state, 'emb-ref', self.admission_for, time.monotonic()+600)
        self.assertEqual(helper.calls, [])


